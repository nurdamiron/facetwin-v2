// Builds icons.js from Hugeicons Free (MIT, https://hugeicons.com), so the app ships inline SVG with no build step.
//   npm pack @hugeicons/core-free-icons && tar xzf hugeicons-core-free-icons-*.tgz
//   node scripts/build-icons.mjs ./package/dist/esm
// To add an icon: add "appName: HugeiconsName" below and re-run. The result (icons.js) is committed.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { CUSTOM } from "./custom-icons.mjs";

const SRC = path.resolve(process.argv[2] || "./package/dist/esm");
const OUT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "icons.js");

const WANT = {
  // actions and navigation
  back: "ArrowLeft01", next: "ArrowRight01", arrow: "ArrowRight02", close: "Cancel01", plus: "PlusSign", check: "Tick02",
  upload: "Upload01", download: "Download01", share: "Share01", heart: "Heart", refresh: "Refresh", undo: "Undo",
  settings: "Settings01", sliders: "SlidersHorizontal", compare: "MoveHorizontal", move3d: "MoveThreeD", info: "InformationCircle",
  play: "Play", pause: "Pause", clock: "Clock01", calendar: "Calendar01", bell: "Bell", mail: "Mail01", trash: "Delete02",
  lock: "Lock", unlock: "LockOpen", shield: "ShieldCheck", camera: "Camera01", image: "Image01", volume: "VolumeHigh", mute: "VolumeMute01",
  fire: "Fire", crown: "Crown", cube: "Cube", sparkles: "Sparkles", star: "Star", gift: "Gift", user: "User02", list: "CheckList",
  trending: "TrendingUp", chart: "Chart01", cart: "HandBag01", copy: "Copy01", link: "Link01", external: "ExternalLink", alert: "Alert02",
  // glow retouch
  onetap: "Sparkles", clearskin: "Clean", undereye: "Eye", wrinkles: "Waves", teeth: "DentalTooth", frecklesOn: "CircleDot",
  frecklesOff: "Eraser", glow: "Sun01",
  // looks
  palette: "Palette", droplet: "Droplet", scissors: "Scissors", hairdryer: "HairDryer", barber: "ChairBarber", wave: "Wave",
  braid: "Link02", layers: "Layers01", brush: "Brush", pencil: "PencilEdit01", glasses: "Glasses", man: "Man", mask: "Mask",
  // coach and routine
  smile: "Smile", face: "FaceMimic", scan: "ScanFace", dumbbell: "Dumbbell01", mic: "Mic01", sun: "Sun02", moon: "Moon01",
  perfume: "Perfume", hairclips: "HairClips", flower: "Flower", zap: "Zap",
};

const kebab = (k) => k.replace(/[A-Z]/g, (c) => "-" + c.toLowerCase());
const out = {};
for (const [name, file] of Object.entries(WANT)) {
  const f = path.join(SRC, `${file}Icon.js`);
  if (!fs.existsSync(f)) { console.error("missing icon:", file); process.exitCode = 1; continue; }
  const mod = await import(pathToFileURL(f).href);
  out[name] = mod.default.map(([tag, attrs]) => {
    const a = Object.entries(attrs).filter(([k]) => k !== "key").map(([k, v]) => `${kebab(k)}="${v}"`).join(" ");
    return `<${tag} ${a}/>`;
  }).join("");
}
Object.assign(out, CUSTOM);
const body = Object.entries(out).map(([k, v]) => `  ${k}: ${JSON.stringify(v)},`).join("\n");
fs.writeFileSync(OUT, `// GENERATED by scripts/build-icons.mjs from Hugeicons Free (MIT). Do not edit by hand.
const PATHS = {
${body}
};

// ico("check", 20) -> inline SVG that takes the text colour (currentColor). size is px or any CSS length.
export function ico(name, size = "1.15em", cls = "") {
  const d = PATHS[name];
  if (!d) { console.warn("[icons] unknown icon", name); return ""; }
  const s = typeof size === "number" ? size + "px" : size;
  return \`<svg class="ic \${cls}" width="\${s}" height="\${s}" viewBox="0 0 24 24" fill="none" aria-hidden="true" focusable="false">\${d}</svg>\`;
}
export const hasIcon = (name) => name in PATHS;
export const ICON_NAMES = Object.keys(PATHS);
`);
console.log("wrote", OUT, Object.keys(out).length, "icons");
